if (isset($_POST['save_macro_action'])) {
    $mode = $_POST['macro_mode']; 
    $macro_num = preg_replace('/[^0-9]/', '', $_POST['macro_num']);

    $conflict = false;
    $conflict_name = "";
    foreach ($tabs_data as $t_idx => $t) {
        foreach ($t['buttons'] as $b_idx => $b) {
            if (isset($b['macro']) && $b['macro'] === $macro_num) {
                if ($mode === 'list' && $_POST['macro_list_sel'] == $t_idx . '_' . $b_idx) {
                    continue;
                }
                $conflict = true;
                $conflict_name = $b['name'];
                break 2;
            }
        }
    }
    
    if ($conflict) {
        echo "<script>alert('".$TDTMF[$lang]['err_macro_used']." $conflict_name.'); window.location.href = window.location.href;</script>"; exit;
    }

    if ($mode === 'list') {
        $parts = explode('_', $_POST['macro_list_sel']);
        $t_idx = (int)$parts[0];
        $b_idx = (int)$parts[1];
        
        if (isset($tabs_data[$t_idx]['buttons'][$b_idx])) {
            if (isset($_POST['edit_old_t_idx']) && $_POST['edit_old_t_idx'] != -1) {
                $o_t = (int)$_POST['edit_old_t_idx'];
                $o_b = (int)$_POST['edit_old_b_idx'];
                if (isset($tabs_data[$o_t]['buttons'][$o_b])) {
                    unset($tabs_data[$o_t]['buttons'][$o_b]['macro']);
                }
            }
            $tabs_data[$t_idx]['buttons'][$b_idx]['macro'] = $macro_num;
        }
    } else {
        $m_type = $_POST['manual_type']; 
        $m_name = trim($_POST['manual_name']);
        $m_tg = preg_replace('/[^0-9]/', '', $_POST['manual_tg']);
        
        $target_tab = -1;
        foreach($tabs_data as $t_idx => $t) {
            if (($t['type'] ?? 'reflector') === $m_type) {
                $target_tab = $t_idx; break;
            }
        }
        if ($target_tab == -1) {
            $tabs_data[] = ['name' => 'Własne ' . ucfirst($m_type), 'type' => $m_type, 'buttons' => []];
            $target_tab = count($tabs_data) - 1;
        }
        $tabs_data[$target_tab]['buttons'][] = [
            'name' => $m_name,
            'tg' => $m_tg,
            'macro' => $macro_num
        ];
    }
    file_put_contents($custom_dtmf_file, json_encode($tabs_data));
    shell_exec('sudo /usr/bin/python3 /usr/local/bin/update_svx_full.py 2>&1');
    shell_exec('sudo /usr/bin/systemctl restart svxlink > /dev/null 2>&1 &');
    echo "<script>window.location.href = window.location.href;</script>"; exit;
}

if (isset($_POST['delete_macro_action'])) {
    $t_idx = (int)$_POST['del_macro_tab'];
    $b_idx = (int)$_POST['del_macro_btn'];
    if (isset($tabs_data[$t_idx]['buttons'][$b_idx])) {
        unset($tabs_data[$t_idx]['buttons'][$b_idx]['macro']);
        file_put_contents($custom_dtmf_file, json_encode($tabs_data));
        shell_exec('sudo /usr/bin/python3 /usr/local/bin/update_svx_full.py 2>&1');
        shell_exec('sudo /usr/bin/systemctl restart svxlink > /dev/null 2>&1 &');
    }
    echo "<script>window.location.href = window.location.href;</script>"; exit;
}

if (isset($_POST['new_tab_name'])) {
    $name = trim($_POST['new_tab_name']);

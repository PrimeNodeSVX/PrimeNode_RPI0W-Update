function switchDtmfMainMode(mode) {
    localStorage.setItem('dtmfMainMode', mode);
    var refBtn = document.getElementById('dtmf-mode-reflector');
    var elBtn = document.getElementById('dtmf-mode-echolink');
    
    if(mode === 'echolink') {
        refBtn.style.color = '#555'; elBtn.style.color = '#2196F3';
        document.getElementById('new_tab_type_hidden').value = 'echolink';
    } else {
        refBtn.style.color = '#4CAF50'; elBtn.style.color = '#555';
        document.getElementById('new_tab_type_hidden').value = 'reflector';
    }

    var tabs = document.getElementsByClassName('dtmf-tab-btn');
    var firstVisible = -1;
    for(var i = 0; i < tabs.length; i++) {
        if(tabs[i].getAttribute('data-type') === mode) {
            tabs[i].style.display = 'inline-block';
            if(firstVisible === -1) firstVisible = tabs[i].id.replace('tab-btn-', '');
        } else {
            tabs[i].style.display = 'none';
        }
    }

    var subtabs = document.getElementsByClassName('dtmf-subtab');
    for(var i = 0; i < subtabs.length; i++) { subtabs[i].style.display = 'none'; }

    var activeDtmfTab = localStorage.getItem('activeDtmfTab');
    var targetTabElement = document.getElementById('tab-btn-' + activeDtmfTab);
    
    if (targetTabElement && targetTabElement.getAttribute('data-type') === mode) {
        openDtmfSubTab(activeDtmfTab);
    } else if (firstVisible !== -1) {
        openDtmfSubTab(firstVisible);
    }
}

function updateMacroTabs() {
    var logic = document.getElementById('macro_logic_sel').value;
    var tabSel = document.getElementById('macro_tab_sel');
    tabSel.innerHTML = '';
    var firstTab = -1;
    
    for(var i=0; i<dtmfTabsData.length; i++) {
        var tType = dtmfTabsData[i].type || 'reflector';
        if(tType === logic) {
            var opt = document.createElement('option');
            opt.value = i;
            opt.text = dtmfTabsData[i].name;
            tabSel.appendChild(opt);
            if(firstTab === -1) firstTab = i;
        }
    }
    
    if(firstTab !== -1) {
        updateMacroBtns();
    } else {
        document.getElementById('macro_list_sel').innerHTML = '<option value="">' + msgNoTabs + '</option>';
    }
}

function updateMacroBtns() {
    var tIdx = document.getElementById('macro_tab_sel').value;
    var btnSel = document.getElementById('macro_list_sel');
    btnSel.innerHTML = '';
    
    if(!dtmfTabsData[tIdx] || !dtmfTabsData[tIdx].buttons) return;
    
    var btns = dtmfTabsData[tIdx].buttons;
    var hasValid = false;
    for(var i=0; i<btns.length; i++) {
        if(btns[i].tg && btns[i].tg !== '') {
            var opt = document.createElement('option');
            opt.value = tIdx + '_' + i;
            var prefix = (dtmfTabsData[tIdx].type === 'echolink') ? 'Node ' : 'TG ';
            opt.text = btns[i].name + ' (' + prefix + btns[i].tg + ')';
            btnSel.appendChild(opt);
            hasValid = true;
        }
    }
    
    if(!hasValid) {
        btnSel.innerHTML = '<option value="">' + msgNoBtns + '</option>';
    }
}

